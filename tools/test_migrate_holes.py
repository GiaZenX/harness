def test_a_number_collision_at_the_merge_is_refused_not_skipped(tmp_path):
    """F4: an existing number is a RESUMPTION only when it is the same entry.

    THE SITUATION IS THE MERGE ITSELF, not a corner case: four streams reserve their numbers by
    hand in their own items, and two of them can pick the same one. MEASURED before this refusal:
    the store carried H151, the document brought a DIFFERENT H151 in the current format, and the
    run answered `0 written, 1 already in the store` with rc 0 -- no item, no prose file, and the
    rewrite of the section removed the entry from the document. Silent data loss on the one run
    the whole migration rests on.

    AND THE RESUMPTION CASE STAYS OPEN, which is the other end: the same entry met twice is still
    a no-op, so an interrupted run resumes.
    """
    _repo, state, doc = project(tmp_path)
    migrate_holes.migrate(state, doc, "PR-0001", apply=True)
    before = sorted(item["id"] for item in state._iter_every_stored_item())

    collision = io.open(doc, encoding="utf-8").read().replace(
        "| Loch | Item | Stand | Titel |",
        "| H1 | **OFFEN** | ein anderer Strom liest es |\n\n| Loch | Item | Stand | Titel |")
    collision = collision.replace(
        "## 13. Danach",
        "### H1 - Ein ANDERER Eintrag unter derselben Nummer - OFFEN\n\n"
        "**Mechanismus:** zwei Stroeme haben dieselbe Nummer reserviert.\n\n"
        "**Urteil: offen.**\n\n## 13. Danach")
    io.open(doc, "w", encoding="utf-8", newline="\n").write(collision)

    with pytest.raises(SystemExit) as refusal:
        migrate_holes.migrate(state, doc, "PR-0001", apply=True)
    message = str(refusal.value)
    assert "H1" in message and "different" in message.lower(), message
    assert "title" in message, "the refusal does not say what differs: %s" % message
    assert sorted(item["id"] for item in state._iter_every_stored_item()) == before, (
        "it wrote something before refusing")
    assert "### H1 - Ein ANDERER" in io.open(doc, encoding="utf-8").read(), (
        "the refused entry was removed from the document anyway -- that is the data loss")


def test_only_a_hole_can_be_filed_as_one_from_the_command_surface(tmp_path):
    """R1 of the round-2 verification: the type check was an enumeration of ONE.

    MEASURED before this was bound to the definition: the only type check was `!= "TSK"`, so
    `capture FR --hole` answered rc 0 `FR-0001 OPEN H3` and `capture DEC --hole` answered rc 0
    `DEC-0001 VALID H4`. Against a migrated store that burnt a hole number nothing can free, left
    `test_every_hole_states_a_verdict_and_an_unclosed_one_names_its_limit` permanently red ("stands
    in 'VALID', which is no status of its type") and would have written the decision into the
    shipped document as a hole. No kernel command deletes an item and `project_memory/` takes no
    tool write, so the repair needs a shell outside the session.

    DRIVEN AS A PROCESS over TWO other types, and the refusal is asked of the KERNEL: a check that
    lived in the parser would be a second spelling of a definition that is right beside it.
    """
    repo, state, _doc = project(tmp_path)
    env = dict(os.environ, PYTHONPATH=TEAM_KITS, PYTHONDONTWRITEBYTECODE="1")

    def capture(item_type, payload):
        return subprocess.run(
            [sys.executable, "-B", "-m", "kernel.cli", "--root", "project_memory",
             "capture", item_type, "--hole"],
            cwd=repo, input=json.dumps(payload), capture_output=True, text=True, env=env,
            timeout=120)

    wish = capture("FR", {"title": "a wish", "request_text": "please"})
    assert wish.returncode != 0, wish.stdout + wish.stderr
    assert "a hole is a BUG" in wish.stderr, wish.stderr

    decision = capture("DEC", {"title": "a decision", "context": "c", "decision": "d",
                               "consequences": "x", "source": "s", "work": "none"})
    assert decision.returncode != 0, decision.stdout + decision.stderr

    # ...and a work order, which never reaches `state.capture` at all. THE TEXT AND THE STORE ARE
    # BOTH ASSERTED, and the round-3 verification is why: with the CLI check removed this line read
    # `returncode != 0` and stayed green, while what really happened was that the ORDER WAS WRITTEN,
    # the flag was silently ignored, and the non-zero exit came from an uncaught `KeyError` further
    # down. A refusal and a crash are not the same answer, and only one of them leaves the store
    # alone.
    order = capture("TSK", dict(TSK_FIELDS_FOR_HOLE_TEST))
    assert order.returncode != 0, order.stdout + order.stderr
    assert "a hole is a BUG" in order.stderr, (
        "the work order was not REFUSED -- this is some other non-zero exit: %s" % order.stderr)
    assert not list(state.iter_active_items("TSK")), (
        "the refused work order was written anyway")

    assert not [item for item in state._iter_every_stored_item()
                if item.get(HOLE_NUMBER_FIELD)], "a number was burnt on a refused capture"
    assert state.next_hole_number() == "H1"


