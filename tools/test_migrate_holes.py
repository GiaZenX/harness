def _kernel_cli(repo, *argv, timeout=120):
    """Run the shipped command surface as a PROCESS -- the way a role reaches it."""
    env = dict(os.environ, PYTHONPATH=TEAM_KITS, PYTHONDONTWRITEBYTECODE="1")
    return subprocess.run(
        [sys.executable, "-B", "-m", "kernel.cli", "--root", "project_memory", *argv],
        cwd=repo, capture_output=True, text=True, env=env, timeout=timeout)


def test_the_kernel_command_migrates_the_holes_and_is_idempotent(tmp_path):
    """The ONE writing run on the route gate 1 sanctions, driven as a process.

    WHY IT IS A KERNEL COMMAND (TSK-0126, merge rework 3): the migration writes canonical state,
    and canonical state has one writer -- `python -B -m kernel.cli --root project_memory
    <command>`. Handing the run to a user for a shell outside Claude Code is a route a REMOTE user
    does not have, so the lead's one line has to be takeable inside a session.

    THE SAME DOOR, not a second one: `tools/migrate_holes.py` calls `kernel.holes` too, which is
    what keeps "two spellings, one behaviour" from being a claim. Measured here through the kernel
    surface only -- the tool's own line is measured by every other node of this file.

    Three properties in one run, because they are one story: without `--apply` nothing is written,
    with it every entry becomes an item and a prose file, and a second run writes nothing.
    """
    repo, state, doc = project(tmp_path)
    before = io.open(doc, encoding="utf-8").read()

    dry = _kernel_cli(repo, "migrate-holes", "--related-pr", "PR-0001")
    assert dry.returncode == 0, dry.stdout + dry.stderr
    assert "3 written" in dry.stdout, dry.stdout
    assert io.open(doc, encoding="utf-8").read() == before, "the dry run wrote the document"
    assert not state.hole_by_number("H1"), "the dry run wrote an item"

    applied = _kernel_cli(repo, "migrate-holes", "--related-pr", "PR-0001", "--apply")
    assert applied.returncode == 0, applied.stdout + applied.stderr
    assert "3 written" in applied.stdout, applied.stdout
    assert state.hole_by_number("H1"), "the writing run left no item"
    assert os.path.isfile(os.path.join(repo, "docs", "holes", "H1.md")), "no prose file"
    after = io.open(doc, encoding="utf-8").read()
    assert "| [H1](docs/holes/H1.md)" in after, after[-400:]

    again = _kernel_cli(repo, "migrate-holes", "--related-pr", "PR-0001", "--apply")
    assert again.returncode == 0, again.stdout + again.stderr
    assert "0 written" in again.stdout, again.stdout
    assert io.open(doc, encoding="utf-8").read() == after, "the second run moved the document"


def test_the_kernel_command_asks_for_the_goal_unless_it_writes_no_item(tmp_path):
    """`--related-pr` is owed by every shape that writes an item, and by no other.

    An item hangs from a goal; `--reindex` writes the pointer index and nothing else, so it is the
    one shape with nothing to hang. Both directions, because a command that demanded the flag
    everywhere would make the index unrepairable and one that demanded it nowhere would file items
    under nothing.
    """
    repo, _state, _doc = project(tmp_path)
    refused = _kernel_cli(repo, "migrate-holes", "--apply")
    assert refused.returncode == 2, refused.stdout + refused.stderr
    assert "--related-pr" in refused.stderr, refused.stderr

    assert _kernel_cli(repo, "migrate-holes", "--related-pr", "PR-0001",
                       "--apply").returncode == 0
    reindexed = _kernel_cli(repo, "migrate-holes", "--reindex")
    assert reindexed.returncode == 0, reindexed.stdout + reindexed.stderr
    assert "index rewritten from the store" in reindexed.stdout, reindexed.stdout


def test_a_new_hole_can_be_filed_from_the_command_surface(tmp_path):
    """F2: there has to be a way to file a NEW hole that is not a hand-numbered heading.

    MEASURED before this existed: the generated index told every reader that new numbers come from
    `capture --hole`, and the shipped parser answered `unrecognized arguments: --hole`. So the only
    working route for a new gap was the `### H<n>` entry with a number chosen by hand -- the very
    defect FR-0087 was written against, restated by a document this migration generates.

    DRIVEN AS A PROCESS, because what has to hold is that a ROLE can type it: the flag, the body on
    stdin, the number in the output, and the number chosen by the kernel and not by the caller.
    """
    repo, state, doc = project(tmp_path)
    migrate_holes.migrate(state, doc, "PR-0001", apply=True)

    body = json.dumps({"title": "a gap measured today", "related_pr": "PR-0001",
                       "observed": "the chain runs", "expected": "it should not",
                       "repro": "run it", "severity": "low",
                       "acceptance_criteria": [{"id": "AC-1", "text": "closed or accepted"}],
                       HOLE_LIMIT_FIELD: "the role says so, no gate"})
    env = dict(os.environ, PYTHONPATH=TEAM_KITS, PYTHONDONTWRITEBYTECODE="1")
    result = subprocess.run(
        [sys.executable, "-B", "-m", "kernel.cli", "--root", "project_memory",
         "capture", "BUG", "--hole"],
        cwd=repo, input=body, capture_output=True, text=True, env=env, timeout=120)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "H4" in result.stdout, result.stdout
    assert "--reindex" in result.stderr, (
        "the caller is not told how the index catches up: %r" % result.stderr)

    filed = [item for item in state._iter_every_stored_item()
             if str(item.get(HOLE_NUMBER_FIELD) or "") == "H4"]
    assert len(filed) == 1 and filed[0]["title"] == "a gap measured today"

    # ...and the number is the kernel's: a caller that tries to choose one is refused
    refused = subprocess.run(
        [sys.executable, "-B", "-m", "kernel.cli", "--root", "project_memory",
         "capture", "BUG", "--hole"],
        cwd=repo, input=json.dumps(json.loads(body) | {HOLE_NUMBER_FIELD: "H99"}),
        capture_output=True, text=True, env=env, timeout=120)
    assert refused.returncode != 0 and HOLE_NUMBER_FIELD in refused.stderr, refused.stderr


def test_a_hole_captured_after_the_migration_reaches_the_generated_index(tmp_path):
    """F3: the index is a VIEW of the store, so it has to be rewritable from the store alone.

    MEASURED before this was fixed: the rewrite of the section sat behind the entry loop, and after
    the one-time migration that loop is empty -- so a hole captured through the kernel was missing
    from the index, the gate test went permanently red, and the remedy that test prints (`re-run
    this with --apply`) changed nothing. Index != generated, before and after the remedy.

    BOTH ROUTES ARE MEASURED, because both are printed to a reader: `--apply` over a document with
    no entries left, and the `--reindex` the capture surface names.

    WHAT IT ASKS OF THE ROW is that the NUMBER and the ITEM are in it, not that the number is a
    link: only the migration writes a prose file, so a hole captured afterwards has none and is
    rendered unlinked (`_prose_link`, and `test_a_hole_with_no_prose_file_is_a_row_without_a_link`
    is that rule's own measurement). Until 2026-09-05 this line asked for the link, and the shipped
    document carried nine rows pointing at files nobody had written.
    """
    repo, state, doc = project(tmp_path)
    migrate_holes.migrate(state, doc, "PR-0001", apply=True)
    fresh = state.capture("BUG", {
        "title": "a gap measured after the migration", "related_pr": "PR-0001",
        "observed": "measured today", "expected": "closed", "repro": "run it", "severity": "low",
        "acceptance_criteria": [{"id": "AC-1", "text": "closed"}],
        HOLE_LIMIT_FIELD: "nothing yet"}, hole=True)
    assert fresh[HOLE_NUMBER_FIELD] not in io.open(doc, encoding="utf-8").read()

    migrate_holes.migrate(state, doc, "PR-0001", apply=True)
    text = io.open(doc, encoding="utf-8").read()
    assert "| %s | %s |" % (fresh[HOLE_NUMBER_FIELD], fresh["id"]) in text, text[-400:]
    lines, start, end = migrate_holes.read_section(doc)
    assert lines[start:end] == migrate_holes.render_index(state)

    # ...and the flag the capture surface points at does the same thing on its own
    io.open(doc, "w", encoding="utf-8", newline="\n").write(
        text.replace("| %s |" % fresh[HOLE_NUMBER_FIELD], "| H999 |", 1))
    result = _kernel_reindex(repo)
    assert result.returncode == 0, result.stdout + result.stderr
    lines, start, end = migrate_holes.read_section(doc)
    assert lines[start:end] == migrate_holes.render_index(state), "the reindex did not restore it"


